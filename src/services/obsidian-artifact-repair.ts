const FRONTMATTER_PATTERN = /^---\n([\s\S]*?)\n---\n*/;
const WIKI_LINK_PATTERN = /\[\[([^\]|#]+)(?:#[^\]|]+)?(?:\|([^\]]+))?\]\]/g;
const FOOTER = '---\n*Generated by ADHD Brain-Twin Gateway.*';

import { buildArtifactDirectoryName } from './vault/filename';

export type ArtifactRepairFile = {
  readonly name: string;
  readonly content: string;
};

export type ArtifactRepairResult = {
  readonly directoryName: string;
  readonly files: readonly ArtifactRepairFile[];
};

type Mention = {
  readonly sourceTitle: string;
  readonly sourceLinkTarget: string;
  readonly excerpt: string;
};

type ParsedArtifactFile = ArtifactRepairFile & {
  readonly type: string;
  readonly title: string;
  readonly stem: string;
  readonly createdAt?: Date;
};

function extractFrontmatter(content: string): string {
  return content.match(FRONTMATTER_PATTERN)?.[1] ?? '';
}

function extractFrontmatterType(content: string): string {
  const typeLine = extractFrontmatter(content).match(/^type:\s+(.+)$/m)?.[1]?.trim();
  return typeLine ?? '';
}

function stripFrontmatter(content: string): string {
  return content.replace(FRONTMATTER_PATTERN, '');
}

function extractTitle(content: string, fallbackStem: string): string {
  const title = stripFrontmatter(content).match(/^#\s+(.+)$/m)?.[1]?.trim();
  return title && title.length > 0 ? title : fallbackStem;
}

function extractCreatedAt(content: string): Date | undefined {
  const createdLine = extractFrontmatter(content).match(/^created:\s+(.+)$/m)?.[1]?.trim();
  if (!createdLine) return undefined;
  const createdAt = new Date(createdLine.replace(/^"|"$/g, ''));
  return Number.isNaN(createdAt.getTime()) ? undefined : createdAt;
}

function parseArtifactFile(file: ArtifactRepairFile): ParsedArtifactFile {
  const stem = file.name.replace(/\.md$/i, '');
  return {
    ...file,
    stem,
    type: extractFrontmatterType(file.content),
    title: extractTitle(file.content, stem),
    createdAt: extractCreatedAt(file.content),
  };
}

function replaceBundlePrefix(content: string, oldDirectoryName: string, newDirectoryName: string): string {
  return content
    .replaceAll(`${oldDirectoryName}/`, '')
    .replaceAll(`${newDirectoryName}/`, '');
}

function normalizeExcerpt(excerpt: string): string {
  return excerpt
    .replace(WIKI_LINK_PATTERN, (_match, rawTarget, rawAlias) => String(rawAlias ?? rawTarget ?? '').trim())
    .replace(/^[-*]\s+/, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 240);
}

function extractMentionExcerpt(content: string, offset: number): string {
  const lineStart = content.lastIndexOf('\n', Math.max(offset - 1, 0));
  const lineEnd = content.indexOf('\n', offset);
  return normalizeExcerpt(content.slice(lineStart + 1, lineEnd === -1 ? content.length : lineEnd));
}

function appendMention(map: Map<string, Mention[]>, targetStem: string, mention: Mention): void {
  const mentions = map.get(targetStem) ?? [];
  const duplicate = mentions.some(existing => (
    existing.sourceLinkTarget === mention.sourceLinkTarget && existing.excerpt === mention.excerpt
  ));
  if (!duplicate) mentions.push(mention);
  map.set(targetStem, mentions);
}

function collectMentions(
  files: readonly ParsedArtifactFile[],
  oldDirectoryName: string
): Map<string, Mention[]> {
  const mentionsByStem = new Map<string, Mention[]>();

  for (const file of files) {
    const sourceLinkTarget = file.stem;
    file.content.replace(
      WIKI_LINK_PATTERN,
      (match, rawTarget, _rawAlias, offset) => {
        const target = String(rawTarget ?? '').trim();
        const prefix = `${oldDirectoryName}/`;
        if (!target.startsWith(prefix)) return match;
        appendMention(mentionsByStem, target.slice(prefix.length), {
          sourceTitle: file.title,
          sourceLinkTarget,
          excerpt: extractMentionExcerpt(file.content, Number(offset)),
        });
        return match;
      }
    );
  }

  return mentionsByStem;
}

function buildLinkedBody(title: string, mentions: readonly Mention[]): string {
  const mentionLines = mentions.flatMap(mention => [
    `- 来源：[[${mention.sourceLinkTarget}|${mention.sourceTitle}]]`,
    `- 摘录：${mention.excerpt}`,
    '',
  ]);
  const coreConclusion = mentions[0]?.excerpt ?? '暂无可直接引用的结论，需补充主报告中的明确表述。';
  return [
    `# ${title}`,
    '',
    '## 核心结论',
    '',
    `- ${coreConclusion}`,
    '',
    '## 证据',
    '',
    ...(mentionLines.length > 0 ? mentionLines.slice(0, -1) : ['- 暂无可用来源摘录。']),
    '',
    FOOTER,
  ].join('\n');
}

// eslint-disable-next-line complexity
function repairLinkedPlaceholder(
  file: ParsedArtifactFile,
  content: string,
  mentionsByStem: Map<string, Mention[]>
): string {
  if (file.type !== 'brain-distill-link') return content;
  if (!content.includes('## 待补充')) return content;
  const frontmatterMatch = content.match(FRONTMATTER_PATTERN)?.[0];
  if (!frontmatterMatch) return content;
  return `${frontmatterMatch}\n${buildLinkedBody(file.title, mentionsByStem.get(file.stem) ?? [])}`;
}

function chooseDirectoryName(files: readonly ParsedArtifactFile[]): string {
  const mainFiles = files
    .filter(file => file.type === 'brain-distill')
    .sort((left, right) => left.name.localeCompare(right.name, 'zh-Hans-CN'));
  const primary = mainFiles[0] ?? files[0];
  if (!primary) throw new Error('Cannot repair an empty artifact directory');
  return buildArtifactDirectoryName(primary.title, primary.createdAt);
}

export function repairLegacyArtifactDirectory(
  directoryName: string,
  files: readonly ArtifactRepairFile[]
): ArtifactRepairResult {
  const parsedFiles = files.map(parseArtifactFile);
  const nextDirectoryName = chooseDirectoryName(parsedFiles);
  const mentionsByStem = collectMentions(parsedFiles, directoryName);

  return {
    directoryName: nextDirectoryName,
    files: parsedFiles.map(file => {
      const rewritten = replaceBundlePrefix(file.content, directoryName, nextDirectoryName);
      return {
        name: file.name,
        content: repairLinkedPlaceholder(file, rewritten, mentionsByStem),
      };
    }),
  };
}